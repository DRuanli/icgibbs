def f3(x, sign=True, nd=3):
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", r"\ensuremath{-}")


def prel(p):
    if p < 0.001:
        return r"\ensuremath{<}0.001"
    return r"\ensuremath{=}" + f"{p:.3f}"


def pval(p):
    return r"\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def ci(c):
    return f"[{f3(c[0])}, {f3(c[1])}]"


def wtl(s):
    return f"{s['win']}/{s['tie']}/{s['loss']}"


def pct(x, nd=0):
    return f"{100 * x:.{nd}f}\\%"


def tex(name, lines):
    with open(os.path.join(PAPER, "tables", name), "w") as f:
        f.write("% generated by paper/scripts/make_v2.py — do not edit\n" + "\n".join(lines) + "\n")


def esc(s):
    return str(s).replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


