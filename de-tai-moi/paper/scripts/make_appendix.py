def tex(name, lines):
    open(os.path.join(T, name), "w").write("\n".join([HDR] + lines) + "\n")


def wtl(c):
    return f"{c['wins']}/{c['ties']}/{c['losses']}"


def s1_secondary():
    r = json.load(open(os.path.join(G8, "g8_confirmatory.json")))
    sec, ex = r["secondary"], r["exploratory"]
    comp = {"llp": "DLLP (linear)", "pu_sar": "nnPU", "pu_scar": "VPU, tuned", "noisy": "CL + TFM", "ssl": "Self-training, tuned"}
    lab = {"llp": "LLP, bag {}", "pu_sar": "PU-SAR, $\\E[e\\mid y=1]={}$", "pu_scar": "PU-SCAR, $c={}$",
           "noisy": "Class-dependent noise, $r={}$", "ssl": "SSL, {} labelled"}
    met = {"llp": "AUC", "pu_sar": "AUC", "pu_scar": "log loss$^\\dagger$", "noisy": "AUC", "ssl": "AUC"}
    out = [r"\begin{tabular}{@{}lllrrrrr@{}}", r"\toprule",
           r"Setting & Metric & Primary comparator & \multicolumn{3}{c}{\ours{} $-$ comparator} & \multicolumn{2}{c}{\ours{} $-$ naive TFM} \\",
           r"\cmidrule(lr){4-6}\cmidrule(l){7-8}", r" & & & $\Delta$ & W/T/L & $p_{\mathrm{Holm}}$ & $\Delta$ & W/T/L \\", r"\midrule"]
    for st in ("llp", "pu_sar", "pu_scar", "noisy", "ssl"):
        for lv, x in sec[st].items():
            lvl = lv if st != "ssl" else f"{float(lv) * 100:.0f}\\%"
            c, nv = x["comparator"], x["naive"]
            out.append(f"{lab[st].format(lvl)} & {met[st]} & {comp[st]} & {f3(c['mean_diff'])} & {wtl(c)} & {fp(c['p_holm'])} & "
                       f"{f3(nv['mean_diff'])} & {wtl(nv)} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_s1_secondary.tex", out)
    d3 = ex["D3"]
    # settings in which the naive labels lose no information: In-Context Gibbs minus naive TFM at every level
    nl = [(st, lv, x["naive"]) for st in ("pu_scar", "noisy", "ssl") for lv, x in sec[st].items()]
    extra = {"s1-nolose-nlev": len(nl), "s1-nolose-nneg": sum(nv["mean_diff"] < 0 for _, _, nv in nl)}
    for st, lv, nv in nl:
        key = {"pu_scar": "puscar", "noisy": "noise", "ssl": "ssl"}[st] + f"{float(lv) * 100:.0f}" if st == "ssl" else \
            {"pu_scar": "puscar", "noisy": "noise", "ssl": "ssl"}[st] + str(lv).replace("0.", "")
        extra[f"s1-{key}-naive-diff"] = f3(nv["mean_diff"])
        extra[f"s1-{key}-naive-wtl"] = wtl(nv)
    return dict(d1=ex["D1"], d2=ex["D2"], d3=d3, extra=extra)


def s1_tabicl(v):
    r = json.load(open(os.path.join(G8, "g8_descriptive.json")))["tabicl_exploratory"]
    s = pd.read_csv(os.path.join(G8, "tabicl_summary.csv"))
    rows = [("LLP, bag 8", r["H2_llp8"], "DLLP (linear)")] + [(f"PLL, $q={q}$", r["H4_pll"][q], "CC, tuned") for q in ("0.3", "0.6")]
    out = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
           r"Setting & Comparator & $\Delta$ [95\% CI] & W/T/L & $p_{\mathrm{Holm}}$ & \multicolumn{3}{c}{mean: \ours{} (TabICL / TabPFN) / oracle (TabICL)} \\",
           r"\midrule"]
    for (lab, x, cn), (_, srow) in zip(rows, s.iterrows()):
        c = x["comparator"]
        out.append(f"{lab} & {cn} & {f3(c['mean_diff'])} [{f3(c['ci_lo'])}, {f3(c['ci_hi'])}] & {wtl(c)} & {fp(c['p_holm'])} & "
                   f"{srow.tabicl_gibbs_warm:.3f} & {srow.tabpfn_gibbs_warm:.3f} & {srow.tabicl_oracle:.3f} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_s1_tabicl.tex", out)
    # largest difference in oracle accuracy/AUC between the two TFMs (clean labels), quoted in the text of Appendix B
    v["s1-tabicl-oracle-maxdiff"] = f"{(s.tabicl_oracle - s.tabpfn_oracle).abs().max():.3f}"


def s2_sensitivity():
    r = json.load(open(os.path.join(S2, "s2_confirmatory.json")))
    rows = [("LLP, bag 8", "DLLP (linear)", r["H2_llp8_S1"]["comparator"], r["H2_llp8_S1"]["naive"], r["H2_llp8"]["comparator"])]
    for q in ("0.3", "0.6"):
        rows.append((f"PLL, $q={q}$", "CC, tuned", r["H4_pll_S1"][q]["comparator"], r["H4_pll_S1"][q]["naive"],
                     r["H4_pll"][q]["comparator"]))
    out = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
           r"Setting & Comparator & datasets & $\Delta$ (all datasets) & $\Delta$ (flagged removed) & W/T/L & $p_{\mathrm{Holm}}$ & $\Delta$ vs naive \\",
           r"\midrule"]
    for lab, cn, c, nv, full in rows:
        out.append(f"{lab} & {cn} & {c['n']} & {f3(full['mean_diff'])} & {f3(c['mean_diff'])} & {wtl(c)} & {fp(c['p_holm'])} & "
                   f"{f3(nv['mean_diff'])} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_s2_s1.tex", out)


def s2_perbaseline():
    p = pd.read_csv(os.path.join(S2, "s2_per_baseline.csv"))
    out = [r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule", r"Setting & Baseline & datasets & $\Delta$ & W/T/L & $p_{\mathrm{Holm}}$ \\",
           r"\midrule"]
    last = None
    for _, x in p.iterrows():
        st = "LLP, bag 8 (AUC)" if x.setting == "llp" else f"PLL, $q={x.level}$ (acc.)"
        if last is not None and st != last:
            out.append(r"\addlinespace")
        pv = fp(x.p_holm)
        pv = r"\textbf{" + pv + "}" if x.p_holm < 0.05 and x.mean_diff > 0 else pv
        out.append(f"{st if st != last else ''} & {BASE[x.baseline]} & {int(x.n)} & {f3(x.mean_diff)} & "
                   f"{int(x.wins)}/{int(x.ties)}/{int(x.losses)} & {pv} \\\\")
        last = st
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_s2_perbase.tex", out)


def s2_per_dataset():
    def short(n):
        return {"hazelnut-spread-contaminant-detection": "hazelnut-contaminant",
                "students_dropout_and_academic_success": "students-dropout"}.get(n, n).replace("_", r"\_")
    l = pd.read_csv(os.path.join(S2, "s2_table_llp8.csv"), index_col=0)
    cols = [("gibbs_warm", "Gibbs"), ("hard_em_warm", "hard-EM"), ("naive", "naive"), ("dllplin_def", "DLLP-lin"),
            ("dllp_tun", "DLLP tuned"), ("llpvat_tun", "LLP-VAT tuned"), ("oracle", "oracle")]
    out = [r"\begin{tabular}{@{}l" + "r" * len(cols) + "@{}}", r"\toprule",
           "Dataset & " + " & ".join(c for _, c in cols) + r" \\", r"\midrule"]
    for ds, x in l.sort_index(key=lambda s: s.str.lower()).iterrows():
        best = max(x[m] for m, _ in cols if m != "oracle")
        cells = [(r"\textbf{%.3f}" % x[m]) if m != "oracle" and abs(x[m] - best) < 1e-12 else f"{x[m]:.3f}" for m, _ in cols]
        out.append(f"{short(ds)} & " + " & ".join(cells) + r" \\")
    out += [r"\midrule", "mean & " + " & ".join(f"{l[m].mean():.3f}" for m, _ in cols) + r" \\", r"\bottomrule", r"\end{tabular}"]
    tex("app_s2_llp_ds.tex", out)
    p = {q: pd.read_csv(os.path.join(S2, f"s2_table_pll_{q}.csv"), index_col=0) for q in (0.3, 0.6)}
    cols = [("gibbs_warm", "Gibbs"), ("hard_em_warm", "hard-EM"), ("naive", "naive"), ("cc_tun", "CC tuned"),
            ("rc_tun", "RC tuned"), ("oracle", "oracle")]
    out = [r"\begin{tabular}{@{}l" + "r" * (2 * len(cols)) + "@{}}", r"\toprule",
           r" & \multicolumn{%d}{c}{$q=0.3$} & \multicolumn{%d}{c}{$q=0.6$} \\" % (len(cols), len(cols)),
           r"\cmidrule(lr){2-%d}\cmidrule(l){%d-%d}" % (len(cols) + 1, len(cols) + 2, 2 * len(cols) + 1),
           "Dataset & " + " & ".join(c for _, c in cols) * 1 + " & " + " & ".join(c for _, c in cols) + r" \\", r"\midrule"]
    for ds in sorted(p[0.3].index, key=str.lower):
        cells = []
        for q in (0.3, 0.6):
            x = p[q].loc[ds]
            best = max(x[m] for m, _ in cols if m != "oracle")
            cells += [(r"\textbf{%.3f}" % x[m]) if m != "oracle" and abs(x[m] - best) < 1e-12 else f"{x[m]:.3f}" for m, _ in cols]
        out.append(f"{short(ds)} & " + " & ".join(cells) + r" \\")
    out += [r"\midrule", "mean & " + " & ".join(f"{p[q][m].mean():.3f}" for q in (0.3, 0.6) for m, _ in cols) + r" \\",
            r"\bottomrule", r"\end{tabular}"]
    tex("app_s2_pll_ds.tex", out)


def rq1(v):
    R = os.path.join(ROOT, "G4", "results", "rq1")
    e1 = pd.read_csv(os.path.join(R, "e1_exact_stationary.csv"))
    e3 = pd.read_csv(os.path.join(R, "e3_thm2_perturbed.csv"))
    e4 = pd.read_csv(os.path.join(R, "e4_thm2_learned_pfn.csv"))
    e5c = pd.read_csv(os.path.join(R, "e5c_block_composition.csv"))
    v["rq1-e1-tvmax"] = f"{e1.tv_stationary_vs_pi.max():.0e}".replace("e-", r"\times10^{-") + "}"
    v["rq1-e1-n"] = str(len(e1))
    both = pd.concat([e3.assign(src="E3"), e4.assign(src="E4")], ignore_index=True)
    both["held"] = (both.tv_actual <= both.bound_thm2_avg + 1e-12).astype(int)
    v["rq1-thm2-n"] = str(len(both))
    v["rq1-thm2-held"] = str(int(both.held.sum()))
    v["rq1-e3-n"] = str(len(e3))
    v["rq1-loose-min"] = f"{both.looseness_avg.min():.1f}"
    v["rq1-loose-max"] = f"{both.looseness_avg.max():.0f}"
    fin = e4[e4.q == "cell_pfn_final"].set_index("kernel")
    v["rq1-pfn-final-single"] = f"{fin.loc['single', 'tv_actual']:.3f}"
    v["rq1-pfn-final-swap"] = f"{fin.loc['swap', 'tv_actual']:.3f}"
    v["rq1-loose-median"] = f"{both.looseness_avg.median():.1f}"
    x = e5c[(e5c.setting == "PU") & (e5c.K == 10)].sort_values("n")
    v["rq1-e5-pred-all-n1000"] = f"{x[x.n == x.n.max()].pred_err_all.iloc[0]:.1e}".replace("e-0", r"\times10^{-").replace("e-", r"\times10^{-") + "}"
    v["rq1-e5-pred-free-n1000"] = f"{x[x.n == x.n.max()].pred_err_free.iloc[0]:.3f}"
    v["rq1-e5-nmax"] = f"{int(x.n.max()):,}".replace(",", "{,}")
    out = [r"\begin{tabular}{@{}lllrrr@{}}", r"\toprule", r"Prior & Weak labels & Kernel & $n$ & states & $\TV(\text{stationary},\pi)$ \\", r"\midrule"]
    for _, r in e1.iterrows():
        wk = str(r.weak).replace("_", r"\_").replace("|", "$|$")
        out.append(f"{'cell' if r.prior == 'cell' else 'mixture'} & {wk} & {r.scheme} & {r.n} & {r.n_states} & "
                   f"{r.tv_stationary_vs_pi:.1e} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_rq1_e1.tex", out)
    g = both.groupby(["src", "kernel"]).agg(n=("tv_actual", "size"), tv=("tv_actual", "median"), bound=("bound_thm2_avg", "median"),
                                             held=("held", "sum"),
                                             loose=("looseness_avg", "median")).reset_index()
    out = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
           r"Conditionals & Kernel & configs & median $\TV(\tilde\pi,\pi)$ & median bound & bound held & median looseness \\", r"\midrule"]
    for _, r in g.iterrows():
        src = "perturbed PPD (incompatible)" if r.src == "E3" else "small PFN (trained)"
        out.append(f"{src} & {r.kernel} & {r.n} & {r.tv:.4f} & {r.bound:.3f} & {r.held}/{r.n} & {r.loose:.1f} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_rq1_thm2.tex", out)


def ablation():
    a = pd.read_csv(os.path.join(G8, "ablation_summary.csv"))
    lab = {"gibbs_warm_K5": "$K=5$ (default 10)", "gibbs_warm_K20": "$K=20$", "gibbs_warm_S15": "15 sweeps (default 30)",
           "gibbs_warm_S60": "60 sweeps", "gibbs_warm_mh": "MH-corrected blocks (exact)", "gibbs_warm_trans": "transductive prediction",
           "gibbs_cold": "cold start", "gibbs_warm_prior1": "PU-SAR prior $N(0,1)$", "gibbs_warm_prior4": "PU-SAR prior $N(0,4^2)$"}
    st = {"llp": "LLP, bag 8", "pll": "PLL", "pu_sar": "PU-SAR"}
    out = [r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule",
           r"Variant (vs.\ default) & Setting & cells & $\Delta$ AUC/acc. & W/T/L & $\Delta$ log loss (+ = better) \\", r"\midrule"]
    for _, r in a.iterrows():
        lv = f", {r.level:g}" if r.setting != "llp" else ""
        out.append(f"{lab[r.variant]} & {st[r.setting]}{lv} & {int(r.n)} & {f3(r.mean_diff)} & {int(r.wins)}/{int(r.ties)}/{int(r.losses)} & "
                   f"{f3(r.mean_diff_logloss)} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    tex("app_ablation.tex", out)


def datasets():
    sys.path.insert(0, os.path.join(ROOT, "G4", "code"))
    from icgibbs.g7.registry import EVAL_BINARY, EVAL_MULTICLASS, S1_EXCLUDE, S2_S1_EXCLUDE, S2_SUBSAMPLE
    h1 = pd.read_csv(os.path.join(ROOT, "docs", "dataset_hashes.csv"))
    h1 = h1[h1.split_set == "eval"].set_index("did")
    h2 = pd.read_csv(os.path.join(ROOT, "S2", "raw", "S2D", "s2_dataset_hashes.csv")).set_index("did")
    fin = pd.read_csv(os.path.join(ROOT, "S2", "s2_final.csv"))
    fin = fin[fin.kept]

    def esc(s):
        return str(s).replace("_", r"\_")

    rows1 = [(did, nm, "binary") for did, (nm, _) in EVAL_BINARY.items()] + [(did, nm, "multiclass") for did, (nm, _) in EVAL_MULTICLASS.items()]
    rows2 = [(int(r.did), r["name"], r.group) for _, r in fin.iterrows()]
    L = []
    for did, nm, _ in rows1:
        x = h1.loc[did]
        L.append((str(did), esc(nm), f"{int(x.n):,}", str(int(x.d)), str(int(x.n_classes)), r"\checkmark" if did in S1_EXCLUDE else ""))
    R = []
    for did, nm, _ in rows2:
        x = h2.loc[did]
        n = S2_SUBSAMPLE.get(did, int(x.n))
        R.append((str(did), esc(nm), f"{n:,}" + ("$^\\ast$" if did in S2_SUBSAMPLE else ""), str(int(x.d)), str(int(x.n_classes)),
                  r"\checkmark" if did in S2_S1_EXCLUDE else ""))
    # full names (review F25): each study in two halves side by side, the studies one below the other
    out = []
    for title, rows in (("Study 1 (OpenML-CC18)", L), ("Study 2 (new curated suites)", R)):
        h = (len(rows) + 1) // 2
        a_, b_ = rows[:h], rows[h:] + [("",) * 6] * (2 * h - len(rows))
        out += [r"\begin{tabular}{@{}rlrrrc@{\hspace{1.2em}}rlrrrc@{}}", r"\toprule",
                rf"\multicolumn{{12}}{{@{{}}l}}{{{title}}} \\", r"\midrule",
                r"ID & name & $n$ & $d$ & $C$ & S1 & ID & name & $n$ & $d$ & $C$ & S1 \\", r"\midrule"]
        out += [" & ".join(x + y) + r" \\" for x, y in zip(a_, b_)]
        out += [r"\bottomrule", r"\end{tabular}", r"\par\medskip"]
    tex("app_datasets.tex", out)


def main():
    os.makedirs(T, exist_ok=True)
    v = {}
    sec = s1_secondary()
    s1_tabicl(v)
    s2_sensitivity()
    s2_perbaseline()
    s2_per_dataset()
    rq1(v)
    ablation()
    datasets()
    v["s1-d1-p"] = f"{sec['d1']['p_one_sided']:.3f}"
    v["s1-d2-p"] = f"{sec['d2']['p_one_sided']:.3f}"
    v["s1-d3-max"] = f3(max(sec["d3"].values()))
    v.update(sec["extra"])
    lines = [HDR, r"\makeatletter"] + [f"\\@namedef{{v@{k}}}{{{x}}}" for k, x in sorted(v.items())] + [r"\makeatother"]
    open(os.path.join(PAPER, "numbers_appendix.tex"), "w").write("\n".join(lines) + "\n")
    print(f"appendix tables written; {len(v)} numbers")


if __name__ == "__main__":
    main()
